export function getPesticidesByMethod(method: string): PesticideDataItem[] {
    if (method === 'all') return PESTICIDE_ANALYSIS_DATA;
    if (method === 'GC') return PESTICIDE_ANALYSIS_DATA.filter(p => p.method === 'GC' || p.method === 'BOTH');
    if (method === 'LC') return PESTICIDE_ANALYSIS_DATA.filter(p => p.method === 'LC' || p.method === 'BOTH');
    return PESTICIDE_ANALYSIS_DATA.filter(p => p.method === method);
}

export function searchPesticides(
    query: string,
    method: string = 'all',
    limit: number = 20
): PesticideDataItem[] {
    if (!query || query.length < 1) return [];
    const q = query.toLowerCase();
    const pool = method === 'all' ? PESTICIDE_ANALYSIS_DATA : getPesticidesByMethod(method);
    return pool.filter(p => p.engName.toLowerCase().includes(q)).slice(0, limit);
}

export interface PesticideStats {
    total: number;
    gc: number;
    lc: number;
    gcOnly: number;
    lcOnly: number;
    both: number;
}

export function getPesticideStats(): PesticideStats {
    const gcOnly = PESTICIDE_ANALYSIS_DATA.filter(p => p.method === 'GC').length;
    const lcOnly = PESTICIDE_ANALYSIS_DATA.filter(p => p.method === 'LC').length;
    const both = PESTICIDE_ANALYSIS_DATA.filter(p => p.method === 'BOTH').length;
    return {
        total: PESTICIDE_ANALYSIS_DATA.length,
        gc: gcOnly + both,
        lc: lcOnly + both,
        gcOnly,
        lcOnly,
        both,
    };
}

